/**
 * Turns a local-mode export ("Export data (JSON)" button) into SQL for Supabase.
 * The SQL REPLACES all file data in the database (profiles and accounts are kept).
 * Run: npm run import:local -- path/to/export.json [out.sql]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { migrate } from '../src/repo/initialState'
import type { AppState } from '../src/types'
import { stateToSql } from './sql_from_state'

const [input, output = input?.replace(/\.json$/i, '') + '.sql'] = process.argv.slice(2)
if (!input) {
  console.error('Usage: npm run import:local -- path/to/export.json [out.sql]')
  process.exit(1)
}

const state = migrate(JSON.parse(readFileSync(input, 'utf8')) as AppState)
if (!state || !Array.isArray(state.files) || !Array.isArray(state.items) || typeof state.statuses !== 'object') {
  console.error(`${input} is not a Department files export.`)
  process.exit(1)
}

const header = `-- Generated by scripts/import_local_export.ts from ${input.split(/[\\/]/).pop()}.\n-- WARNING: replaces all file data in the database.\n\n`
writeFileSync(output, header + stateToSql(state, 'replace'))
console.log(`Wrote ${output}: ${state.files.length} files, ${state.items.length} items, ${Object.keys(state.statuses).length} statuses, ${state.activity.length} log entries`)
