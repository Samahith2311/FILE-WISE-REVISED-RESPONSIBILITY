/**
 * Writes supabase/seed.sql from src/data/seed.json: the 2026-27 year, faculty,
 * criteria, files and checklist items. Safe to run twice (existing rows are kept).
 * Run: npm run seed:sql
 */
import { writeFileSync } from 'node:fs'
import { initialState } from '../src/repo/initialState'
import { stateToSql } from './sql_from_state'

const out = new URL('../supabase/seed.sql', import.meta.url)
const header = '-- Generated by scripts/build_seed_sql.ts from src/data/seed.json. Do not edit by hand.\n\n'
writeFileSync(out, header + stateToSql(initialState(), 'seed'))
console.log('Wrote supabase/seed.sql')
